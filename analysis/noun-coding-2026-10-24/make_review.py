#!/usr/bin/env python3
"""Write REVIEW.md from draft_coding.py's outputs: one entry per feature, listing
the rows proposed as y and marginal (n is the rest), with the basis, so Brett
can judge a column at a time. Run after draft_coding.py."""
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent

rows = list(csv.reader((HERE / "proposed-new-rows.csv").open()))
cols = list(csv.reader((HERE / "proposed-new-columns.csv").open()))
notes = {}
for r in csv.DictReader((HERE / "feature-notes.csv").open()):
    notes.setdefault(r["feature"], {})[r["part"]] = r["note"]
added = {r["feature"]: r for r in csv.DictReader((HERE / "features-added.csv").open())}


def by_value(table, j):
    out = {"y": [], "marginal": [], "": []}
    for r in table[1:]:
        if r[j] in out:
            out[r[j]].append(r[0])
    return out


def line(label, vals):
    parts = []
    for k, name in (("y", "y"), ("marginal", "marginal"), ("", "blank")):
        if vals[k]:
            parts.append(f"{name}: {', '.join(vals[k])}")
    return f"- {label}: " + ("; ".join(parts) if parts else "all n")


out = ["# Noun coding: review sheet",
       "<!-- SUMMARY: generated by make_review.py from the draft coding; one entry per feature with the rows proposed y or marginal, for Brett to judge a column at a time · status: on hold, superseded by the codebook · updated: 2026-10-24 -->",
       "",
       "**On hold: superseded by the codebook (24 Oct); don't judge these cells yet. See README.md.**",
       "",
       "Everything here is Claude's proposal. n is every row not listed. Row names: lot, number, plenty, dozen, majority, dog, water, Kim, Toronto, numerous, rich, tall, and the category rows CN, PN, ADJ (any common noun, proper noun, or adjective may). Change values in `draft_coding.py` and rerun both scripts, or mark corrections here and Claude will apply them.",
       "",
       "## The 105 existing features, for the fifteen new rows", ""]
h = rows[0]
for j, f in enumerate(h[1:], start=1):
    if f in added:
        continue
    out.append(f"### {f}")
    out.append(line("new rows", by_value(rows, j)))
    if notes.get(f, {}).get("new rows"):
        out.append(f"- basis: {notes[f]['new rows']}")
    out.append("")
out += ["## The ten added features (from CGEL's lists)", ""]
hc = cols[0]
for f in hc[1:]:
    out.append(f"### {f}")
    out.append(f"- definition: {added[f]['definition']} ({added[f]['source']})")
    out.append(line("new rows", by_value(rows, h.index(f))))
    if notes.get(f, {}).get("new rows"):
        out.append(f"- basis, new rows: {notes[f]['new rows']}")
    out.append(line("existing forms", by_value(cols, hc.index(f))))
    if notes.get(f, {}).get("existing forms"):
        out.append(f"- basis, existing forms: {notes[f]['existing forms']}")
    out.append("")
(HERE / "REVIEW.md").write_text("\n".join(out))
print(f"wrote REVIEW.md ({len(out)} lines)")
