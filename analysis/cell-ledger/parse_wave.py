#!/usr/bin/env python3
"""Parse a blind-coding wave made by make_packets.py (24 Oct 2026).

Usage: python3 analysis/cell-ledger/parse_wave.py RUN_DIR
RUN_DIR holds wave2-map.json and wave2-pN/{CODEX,MUSE,CLAUDE}.md.
Writes analysis/cell-ledger/coder-cells-wave2.csv and RUN_DIR/COMPARISON.md:
agreement among coders, calibration of the pronoun and determinative forms
against Brett's 2021 cells, and the reference-set cells by consensus.
"""
import csv
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
REVERSED = {"must_be_outranked_by_a_coindexed_element"}  # coded in possibility form
# Cells where a definition still shows the coder the answer (wave 3: the definite
# column's "the dog" and the head rule's "quite the scholar"); left out of calibration.
EXCLUDE = {"wave3": {("the", c) for c in ("definite", "takes_adverb_quite_as_a_modifier", "can_be_modified_by_almost",
                                          "can_be_modified_by_approximately", "can_be_modified_by_hardly", "at_least_focus")}}


def parse(path):
    codes, notes, frames, section = {}, [], [], None
    for line in path.read_text().replace("−", "-").splitlines():
        s = line.strip().strip("`")
        if s in ("CODES", "NOTES", "FRAMES"):
            section = s
            continue
        if section == "CODES":
            m = re.match(r"(R\d\d)\s*:\s*(.+)", s)
            if m:
                codes[m.group(1)] = re.findall(r"\b[ymnx]\b", m.group(2))
        elif section == "NOTES" and "|" in s:
            p = [x.strip() for x in s.split("|")]
            if re.match(r"R\d\d$", p[0]):
                notes.append(p)
        elif section == "FRAMES" and s:
            frames.append(s)
    return codes, notes, frames


def main():
    run = Path(sys.argv[1])
    mapfile = next(run.glob("*-map.json"))
    prefix = mapfile.name.replace("-map.json", "")
    mp = json.loads(mapfile.read_text())
    rows = mp["rows"]
    m = list(csv.reader((ROOT / "analysis" / "matrix-2026-10" / "matrix-2026-10.csv").open()))
    h, mrows = m[0], {r[0]: r for r in m[1:]}
    cells = defaultdict(dict)       # (form, column) -> coder -> value
    notes_ix = defaultdict(list)
    report = [f"# Blind coding, {prefix.replace('wave', 'wave ')}: comparison", "",
              "Generated by analysis/cell-ledger/parse_wave.py. Values: y, m (degraded), n, x (not applicable).", "",
              "## Parsing"]
    frames_all = []
    out = []
    for pk, cmap in mp["packets"].items():
        codes_order = list(cmap)
        for coder in ("CODEX", "MUSE", "CLAUDE"):
            f = run / f"{prefix}-{pk}" / f"{coder}.md"
            if not f.exists():
                report.append(f"- {pk} {coder}: missing")
                continue
            codes, notes, frames = parse(f)
            ok = sum(len(v) == len(codes_order) for v in codes.values())
            report.append(f"- {pk} {coder}: {len(codes)} rows, {ok} with the right length, {len(notes)} notes, {len(frames)} frames")
            frames_all += [f"{coder}: {x}" for x in frames]
            for n in notes:
                if n[1] in cmap:
                    notes_ix[(rows.get(n[0]), cmap[n[1]], coder)].append(" | ".join(n[2:]))
            for rid, vals in codes.items():
                if rid not in rows or len(vals) != len(codes_order):
                    continue
                for code, v in zip(codes_order, vals):
                    col = cmap[code]
                    cells[(rows[rid], col)][coder] = v
                    out.append({"form": rows[rid], "column": col, "frame": "default", "value": v,
                                "status": "proposed", "evidence_type": "blind coder",
                                "note": " / ".join(notes_ix.get((rows[rid], col, coder), [])),
                                "proposer": f"blind coder {coder} ({prefix}, 2026-10-24)", "date": "2026-10-24"})
    with (HERE / f"coder-cells-{prefix}.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out[0]) if out else ["form"])
        w.writeheader()
        w.writerows(out)

    full = {k: v for k, v in cells.items() if len(v) == 3}
    agree = sum(len(set(v.values())) == 1 for v in full.values())
    report += ["", "## Agreement", f"- {agree} of {len(full)} cells coded by all three coders are unanimous."]
    split_by_col = Counter(c for (f, c), v in full.items() if len(set(v.values())) > 1)
    report.append("- most split columns: " + ", ".join(f"{c} {n}" for c, n in split_by_col.most_common(12)))

    report += ["", "## Calibration against Brett's 2021 cells (pronoun and determinative forms)"]
    for coder in ("CODEX", "MUSE", "CLAUDE"):
        hit = tot = 0
        miss = []
        for (form, col), v in cells.items():
            if form not in mrows or col not in h or coder not in v or (form, col) in EXCLUDE.get(prefix, set()):
                continue
            v21 = mrows[form][h.index(col)]
            v21 = {"marginal": "m"}.get(v21, v21)
            if col in REVERSED:
                v21 = {"y": "n", "n": "y"}.get(v21, v21)
            vc = v[coder]
            vcmp = "n" if vc == "x" else vc
            tot += 1
            good = vcmp == v21 or (vcmp == "m" and v21 == "y")
            hit += good
            if not good:
                miss.append(f"{form} {col}: {vc} (2021 {v21})")
        report.append(f"- {coder}: {hit} of {tot} match (m matches a 2021 y; x matches a 2021 n).")
        if miss:
            report.append("  - mismatches: " + "; ".join(miss))

    ex = EXCLUDE.get(prefix)
    if ex:
        report.append(f"- left out of calibration ({len(ex)} cells whose definitions show the answer): "
                      + "; ".join(f"{f} {c}" for f, c in sorted(ex)))
    against = []
    for (form, col), v in sorted(full.items()):
        if form not in mrows or col not in h or len(set(v.values())) > 1:
            continue
        v21 = {"marginal": "m"}.get(mrows[form][h.index(col)], mrows[form][h.index(col)])
        vc = next(iter(v.values()))
        if ("n" if vc == "x" else vc) != v21 and not (vc == "m" and v21 == "y"):
            against.append(f"- {form} {col}: all three {vc}, 2021 {v21}")
    report += ["", "## All three coders agree against the 2021 cell",
               "Candidates for the codebook's section 8 (reopened 2021 cells); not judgments."] + (against or ["- none"])
    report += ["", "## Reference rows: consensus and splits",
               "Unanimous y or n cells are listed by count; splits and every m are listed in full with notes.", ""]
    ref = [f for f in rows.values() if f not in mrows]
    for form in ref:
        fc = {c: v for (f, c), v in full.items() if f == form}
        un = Counter(next(iter(set(v.values()))) for v in fc.values() if len(set(v.values())) == 1)
        report.append(f"### {form}")
        report.append(f"- unanimous: " + ", ".join(f"{k} {n}" for k, n in sorted(un.items())))
        for c, v in sorted(fc.items()):
            if len(set(v.values())) > 1 or "m" in v.values():
                ns = "; ".join(f"{k}: {'/'.join(notes_ix.get((form, c, k), [])) or '-'}" for k in v)
                report.append(f"- {c}: " + ", ".join(f"{k} {x}" for k, x in v.items()) + f" — {ns}")
        report.append("")
    report += ["## Proposed frames and readings"] + [f"- {x}" for x in frames_all]
    (run / "COMPARISON.md").write_text("\n".join(report) + "\n")
    print(f"{len(out)} coder cells; {agree}/{len(full)} unanimous; report {run / 'COMPARISON.md'}")


if __name__ == "__main__":
    main()
