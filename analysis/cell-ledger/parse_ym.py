#!/usr/bin/env python3
"""Parse the y-to-m grading pass (24 Oct 2026): Brett's 2021 y cells graded
y / m / n by blind coders. Usage: python3 analysis/cell-ledger/parse_ym.py RUN_DIR
RUN_DIR holds ym-map.json and ym-pN/{MUSE,CLAUDE}.md. Writes
analysis/cell-ledger/coder-cells-ym.csv and RUN_DIR/YM-SUMMARY.md, which lists
every cell any coder graded m or n, for Brett."""
import csv
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def parse(path):
    grades, notes, section = {}, [], None
    for line in path.read_text().splitlines():
        s = line.strip().strip("`")
        if s in ("GRADES", "NOTES"):
            section = s
            continue
        if section == "GRADES":
            m = re.match(r"(C\d\d)\s*:\s*(.+)", s)
            if m:
                for fid, v in re.findall(r"(F\d{3})\s+([ymn])\b", m.group(2)):
                    grades[(m.group(1), fid)] = v
        elif section == "NOTES" and "|" in s:
            p = [x.strip() for x in s.split("|")]
            if re.match(r"F\d{3}$", p[0]) and re.match(r"C\d\d$", p[1]):
                notes.append(p)
    return grades, notes


def main():
    run = Path(sys.argv[1])
    mp = json.loads((run / "ym-map.json").read_text())
    forms = mp["forms"]
    m = list(csv.reader((ROOT / "analysis" / "matrix-2026-10" / "matrix-2026-10.csv").open()))
    h, y21 = m[0], set()
    for r in m[1:]:
        y21 |= {(r[0], c) for c, v in zip(h, r) if v == "y"}
    cells = defaultdict(dict)
    notes = defaultdict(dict)
    out, parsing = [], []
    for pk, info in mp["packets"].items():
        cmap = info["columns"]
        for coder in ("MUSE", "CLAUDE"):
            f = run / f"ym-{pk}" / f"{coder}.md"
            if not f.exists():
                parsing.append(f"- {pk} {coder}: missing")
                continue
            g, ns = parse(f)
            for n in ns:
                if n[1] in cmap:
                    notes[(forms.get(n[0]), cmap[n[1]])][coder] = " | ".join(n[2:])
            stray = 0
            for (code, fid), v in g.items():
                if code not in cmap or fid not in forms:
                    continue
                key = (forms[fid], cmap[code])
                if key not in y21:      # graded a form the column didn't list
                    stray += 1
                    continue
                cells[key][coder] = v
                out.append({"form": key[0], "column": key[1], "frame": "default", "value": v,
                            "status": "proposed", "evidence_type": "blind grading of a 2021 y",
                            "note": notes.get(key, {}).get(coder, ""),
                            "proposer": f"blind coder {coder} (y-to-m pass, 2026-10-24)", "date": "2026-10-24"})
            parsing.append(f"- {pk} {coder}: {len(g) - stray} of {info['cells']} cells graded, {len(ns)} notes"
                           + (f" ({stray} grade for an unlisted form dropped)" if stray else ""))
    with (HERE / "coder-cells-ym.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out[0]) if out else ["form"])
        w.writeheader()
        w.writerows(out)
    flagged = {k: v for k, v in cells.items() if set(v.values()) - {"y"}}
    both = {k: v for k, v in cells.items() if len(v) == 2}
    L = ["# The y-to-m pass: Brett's 2021 y cells graded blind",
         "<!-- SUMMARY: every 2021 y cell that a blind coder graded m or n, with both coders' grades and notes, for Brett to judge · status: for Brett · updated: 2026-10-24 -->", "",
         "Generated by analysis/cell-ledger/parse_ym.py. Coders: Muse Wonder 1.0 and Claude Opus 5.5 (subagents). Grades: y fully available, m degraded, n not available. Notes are model output, unedited.", "",
         "## Parsing"] + parsing + ["",
         "## Counts",
         f"- cells graded by both coders: {len(both)}",
         f"- both y: {sum(set(v.values()) == {'y'} for v in both.values())}",
         f"- at least one m: {sum('m' in v.values() for v in both.values())}; both m: {sum(set(v.values()) == {'m'} for v in both.values())}",
         f"- at least one n: {sum('n' in v.values() for v in both.values())}; both n: {sum(set(v.values()) == {'n'} for v in both.values())}",
         "", "## Flagged cells (any m or n), by column", ""]
    by_col = defaultdict(list)
    for (form, col), v in sorted(flagged.items()):
        by_col[col].append((form, v))
    for col, items in sorted(by_col.items()):
        L.append(f"### {col}")
        for form, v in items:
            ns = "; ".join(f"{k}: {notes.get((form, col), {}).get(k, '-')}" for k in v)
            L.append(f"- {form}: " + ", ".join(f"{k} {x}" for k, x in v.items()) + f" — {ns}")
        L.append("")
    (run / "YM-SUMMARY.md").write_text("\n".join(L) + "\n")
    print(f"{len(out)} graded cells; {len(flagged)} flagged; summary {run / 'YM-SUMMARY.md'}")


if __name__ == "__main__":
    main()
