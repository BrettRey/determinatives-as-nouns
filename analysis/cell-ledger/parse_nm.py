#!/usr/bin/env python3
"""Parse the n-to-m pass (24 Oct 2026): Brett's 2021 n cells graded y / m / n.

Usage: python3 analysis/cell-ledger/parse_nm.py RUN_DIR
RUN_DIR holds nm-map.json, nm-pN/MUSE.md (the screen) and, once the second
pass has run, second-pK/CLAUDE.md with second-map.json (claim shown) and
neutral-pK/CLAUDE.md with neutral-map.json (same cells, no claim shown). Writes
analysis/cell-ledger/coder-cells-nm.csv and RUN_DIR/NM-SUMMARY.md.
"""
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
# Columns changed after the Muse screen's packets were built (24 Oct): negative
# narrowed to outright negation; partitive heading made derived. Their screen
# grades answer the old definition, so they're dropped here and from the second pass.
STALE = {"negative", "functions_as_head_of_partitive_construction"}
sys.path.insert(0, str(HERE))
from parse_ym import parse  # noqa: E402  (same GRADES / NOTES format)


def read(run, mapname, prefix, coder):
    mp = json.loads((run / mapname).read_text())
    forms = mp["forms"]
    cells, notes, parsing = {}, {}, []
    for pk, info in mp["packets"].items():
        f = run / f"{prefix}-{pk}" / f"{coder}.md"
        if not f.exists():
            parsing.append(f"- {prefix}-{pk} {coder}: missing")
            continue
        g, ns = parse(f)
        listed = set(map(tuple, info.get("listed", []))) or None
        stray = 0
        for (code, fid), v in g.items():
            if code not in info["columns"] or fid not in forms:
                continue
            key = (forms[fid], info["columns"][code])
            if listed is not None and key not in listed:
                stray += 1
                continue
            cells[key] = v
        for n in ns:
            if n[1] in info["columns"] and n[0] in forms:
                notes[(forms[n[0]], info["columns"][n[1]])] = " | ".join(n[2:])
        parsing.append(f"- {prefix}-{pk} {coder}: {len(g) - stray} of {info['cells']} cells graded, {len(ns)} notes"
                       + (f" ({stray} grades for unlisted cells dropped)" if stray else ""))
    return cells, notes, parsing


def main():
    run = Path(sys.argv[1])
    m = list(csv.reader((ROOT / "analysis" / "matrix-2026-10" / "matrix-2026-10.csv").open()))
    h = m[0]
    n21 = {(r[0], c) for r in m[1:] for c, v in zip(h, r) if v == "n"}
    muse, mnotes, parsing = read(run, "nm-map.json", "nm", "MUSE")
    dropped = sum(1 for k in muse if k[1] in STALE)
    muse = {k: v for k, v in muse.items() if k in n21 and k[1] not in STALE}
    parsing.append(f"- {dropped} screen grades in columns changed after the screen ({', '.join(sorted(STALE))}) dropped")
    claude, cnotes, p2 = ({}, {}, [])
    if (run / "second-map.json").exists():
        claude, cnotes, p2 = read(run, "second-map.json", "second", "CLAUDE")
    neut, nnotes, p3 = ({}, {}, [])
    if (run / "neutral-map.json").exists():
        neut, nnotes, p3 = read(run, "neutral-map.json", "neutral", "CLAUDE")
        p2 += p3
    out = []
    for coder, cells, notes, label in (("MUSE", muse, mnotes, "n-to-m screen"), ("CLAUDE", claude, cnotes, "n-to-m second pass, claim shown"),
                                       ("CLAUDE", neut, nnotes, "n-to-m second pass, no claim shown")):
        for (form, col), v in sorted(cells.items()):
            out.append({"form": form, "column": col, "frame": "default", "value": v, "status": "proposed",
                        "evidence_type": "blind grading of a 2021 n", "note": notes.get((form, col), ""),
                        "proposer": f"blind coder {coder} ({label}, 2026-10-24)", "date": "2026-10-24"})
    with (HERE / "coder-cells-nm.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(out[0]))
        w.writeheader()
        w.writerows(out)
    mc = Counter(muse.values())
    L = ["# The n-to-m pass: Brett's 2021 n cells graded blind",
         "<!-- SUMMARY: counts from the n-to-m pass (Muse screen of every 2021 n cell in 44 columns; Claude second pass on Muse's flags and a random tenth of the rest) · status: for Brett · updated: 2026-10-24 -->", "",
         "Generated by analysis/cell-ledger/parse_nm.py. Notes are model output.", "", "## Parsing"] + parsing + p2 + ["",
         "## Muse screen", f"- {len(muse)} cells: n {mc['n']}, m {mc['m']}, y {mc['y']}"]
    if claude:
        both = {k: (muse[k], claude[k]) for k in claude if k in muse}
        flagged = {k: v for k, v in both.items() if v[0] != "n"}
        sample = {k: v for k, v in both.items() if v[0] == "n"}
        L += ["", "## Second pass (Claude, blind to Muse's grades)",
              f"- on Muse's flags ({len(flagged)}): Claude " + ", ".join(f"{x} {n}" for x, n in sorted(Counter(v[1] for v in flagged.values()).items())),
              f"- on the random tenth of Muse's n's ({len(sample)}): Claude " + ", ".join(f"{x} {n}" for x, n in sorted(Counter(v[1] for v in sample.values()).items())),
              "  (Claude's m and y here estimate what the screen misses.)"]
        agree = {k: v for k, v in both.items() if v[0] != "n" and v[1] != "n"}
        L += ["", f"## Both coders m or y ({len(agree)}): candidates for Brett", ""]
        by = defaultdict(list)
        for (f, c), v in sorted(agree.items()):
            by[c].append(f"- {f}: Muse {v[0]}, Claude {v[1]}. Muse: {mnotes.get((f, c), '-')}; Claude: {cnotes.get((f, c), '-')}")
        for c in sorted(by):
            L += [f"### {c}"] + by[c] + [""]
    if claude and neut:
        same = [k for k in claude if k in neut]
        tab = Counter((claude[k], neut[k]) for k in same)
        cm, nm_ = Counter(claude[k] for k in same), Counter(neut[k] for k in same)
        L += ["## Framing: the same Claude coder with and without the claim shown", "",
              f"On {len(same)} identical cells. Claim shown: " + ", ".join(f"{x} {cm[x]}" for x in "ynm") +
              ". No claim shown: " + ", ".join(f"{x} {nm_[x]}" for x in "ynm") + ".",
              f"Agreement {sum(v for (a, b), v in tab.items() if a == b)} of {len(same)}.", "",
              "| claim shown \\ no claim | y | m | n |", "|---|---|---|---|"]
        L += [f"| {a} | " + " | ".join(str(tab[(a, b)]) for b in "ymn") + " |" for a in "ymn"]
        L.append("")
    (run / "NM-SUMMARY.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[5:12 + (5 if claude else 0)]))


if __name__ == "__main__":
    main()
