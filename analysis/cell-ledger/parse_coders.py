#!/usr/bin/env python3
"""Parse the blind coders' outputs (pilot of 24 Oct 2026) into ledger rows,
compare the coders with one another, and calibrate them against Brett's 2021
cells where a pilot column corresponds to a 2021 column.

Usage: python3 analysis/cell-ledger/parse_coders.py RUN_DIR
RUN_DIR holds CODEX.md, MUSE.md, CLAUDE.md (each the coder's verbatim output).
Writes analysis/cell-ledger/coder-cells.csv and RUN_DIR/COMPARISON.md.
"""
import csv
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

ORDER = "A+ A- B+ B- C+ C- S+ S- G1 G2 N1 N2 P1 E1 R1 E2 L1 T1".split()
FORMS = {
    "F01": "lot", "F02": "number", "F03": "plenty", "F04": "dozen", "F05": "dozens", "F06": "majority",
    "F07": "dog", "F08": "dogs", "F09": "water", "F10": "Kim", "F11": "Toronto", "F12": "numerous",
    "F13": "multiple", "F14": "countless", "F15": "rich", "F16": "poor", "F17": "tall",
    "F18": "few", "F19": "many", "F20": "some", "F21": "all", "F22": "each", "F23": "every",
    "F24": "the", "F25": "a", "F26": "this", "F27": "these", "F28": "someone", "F29": "something",
    "F30": "she", "F31": "her_acc", "F32": "it_plain", "F33": "they_plur", "F34": "which_int_det",
    "F35": "we_det",
}
FRAME = {"A": "independent_argument", "B": "predicative_complement", "C": "fixed_PP", "S": "set_denoting_use"}
COLUMN = {
    "+": "heads_nominal_after_separate_determiner", "-": "heads_NP_with_no_determiner",
    "G1": "personal_gender_as_head_or_fused_head", "G2": "non_personal_gender",
    "N1": "semantically_singular", "N2": "semantically_plural",
    "P1": "may_follow_particle_unstressed_as_object", "E1": "takes_prehead_AdjP_modifier",
    "R1": "takes_relative_clause_modifier", "E2": "takes_post_head_AdjP",
    "L1": "takes_ly_adverb_modifier", "T1": "functions_as_head_of_partitive_construction",
}
# Pilot columns that correspond to 2021 columns, with the conversion of the 2021 value.
CALIB = {
    "G1": ("personal_gender_as_head_or_fused_head", lambda v: v),
    "G2": ("non_personal_gender", lambda v: v),
    "N1": ("semantically_singular", lambda v: v),
    "N2": ("semantically_plural", lambda v: v),
    "T1": ("functions_as_head_of_partitive_construction", lambda v: v),
    "P1": ("Must_be_stressed_as_object_after_particle", lambda v: {"y": "n", "n": "y"}.get(v, v)),
}


def col_frame(code):
    if code[0] in FRAME and code[1:] in ("+", "-"):
        return COLUMN[code[1:]], FRAME[code[0]]
    return COLUMN[code], "default"


def parse(path):
    text = path.read_text().replace("−", "-")
    codes, notes, frames = {}, [], []
    section = None
    for line in text.splitlines():
        s = line.strip().strip("`")
        if s in ("CODES", "NOTES", "FRAMES"):
            section = s
            continue
        if section == "CODES":
            m = re.match(r"(F\d\d)\s*:\s*(.+)", s)
            if m:
                vals = re.findall(r"\b[ymnx]\b", m.group(2))
                if len(vals) >= 18:
                    codes[m.group(1)] = vals[:18]
        elif section == "NOTES" and "|" in s:
            parts = [p.strip() for p in s.split("|")]
            if re.match(r"F\d\d$", parts[0]):
                notes.append(parts)
        elif section == "FRAMES" and s:
            frames.append(s)
    return codes, notes, frames


def main():
    run = Path(sys.argv[1])
    coders = {}
    for name in ("CODEX", "MUSE", "CLAUDE"):
        p = run / f"{name}.md"
        if p.exists():
            coders[name] = parse(p)
    m = list(csv.reader((ROOT / "analysis" / "matrix-2026-10" / "matrix-2026-10.csv").open()))
    h, mrows = m[0], {r[0]: r for r in m[1:]}

    out = []
    for name, (codes, notes, _) in coders.items():
        note_ix = defaultdict(list)
        for n in notes:
            note_ix[(n[0], n[1].replace("−", "-"))].append(" | ".join(n[2:]))
        for fid, vals in codes.items():
            for code, v in zip(ORDER, vals):
                col, frame = col_frame(code)
                out.append({"form": FORMS[fid], "column": col, "frame": frame, "value": v,
                            "status": "proposed", "evidence_type": "blind coder",
                            "note": " / ".join(note_ix.get((fid, code), [])),
                            "proposer": f"blind coder {name} (pilot 2026-10-24)", "date": "2026-10-24"})
    with (HERE / "coder-cells.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["form", "column", "frame", "value", "status", "evidence_type",
                                           "note", "proposer", "date"])
        w.writeheader()
        w.writerows(out)

    lines = ["# Blind-coding pilot: comparison", "",
             "Generated by analysis/cell-ledger/parse_coders.py. Values: y, m (degraded), n, x (not applicable).", ""]
    lines.append("## Parsing")
    for name, (codes, notes, frames) in coders.items():
        lines.append(f"- {name}: {len(codes)} of 35 forms parsed, {len(notes)} notes, {len(frames)} frame proposals")
    lines.append("")

    # agreement among coders
    names = list(coders)
    lines.append("## Agreement among coders (cells where all coders gave a value)")
    agree = Counter()
    disagreements = []
    for fid in FORMS:
        for k, code in enumerate(ORDER):
            vals = [coders[n][0][fid][k] for n in names if fid in coders[n][0]]
            if len(vals) == len(names):
                agree["all" if len(set(vals)) == 1 else "split"] += 1
                if len(set(vals)) > 1:
                    disagreements.append((FORMS[fid], code, dict(zip(names, vals))))
    tot = sum(agree.values())
    lines.append(f"- {agree['all']} of {tot} cells unanimous; {agree['split']} split.")
    by_col = Counter(c for _, c, _ in disagreements)
    lines.append("- splits by column: " + ", ".join(f"{c} {n}" for c, n in by_col.most_common()))
    lines.append("")

    # calibration against 2021
    lines.append("## Calibration against Brett's 2021 cells")
    for name in names:
        hit = tot2 = 0
        misses = []
        for fid, form in FORMS.items():
            if form not in mrows or fid not in coders[name][0]:
                continue
            for code, (c2021, conv) in CALIB.items():
                k = ORDER.index(code)
                v2021 = conv(mrows[form][h.index(c2021)])
                vc = coders[name][0][fid][k]
                if code == "P1" and vc == "x":
                    vc_cmp = "y"  # 2021 "not must-be-stressed" covers forms that can't be objects
                elif vc == "x":
                    vc_cmp = "n"  # the 2021 matrix had no x: a property that can't arise was coded n
                else:
                    vc_cmp = vc
                tot2 += 1
                hit += (vc_cmp == v2021) or (vc_cmp == "m" and v2021 == "y")
                if not ((vc_cmp == v2021) or (vc_cmp == "m" and v2021 == "y")):
                    misses.append(f"{form} {code}: coder {vc}, 2021 {v2021}")
        gender = [x for x in misses if " G1:" in x or " G2:" in x]
        other = [x for x in misses if x not in gender]
        lines.append(f"- {name}: {hit} of {tot2} cells match (m counts as matching a 2021 y, x as a 2021 n); "
                     f"{len(gender)} of the mismatches are gender, {len(other)} other.")
        if gender:
            lines.append("  - gender: " + "; ".join(gender))
        if other:
            lines.append("  - other: " + "; ".join(other))
    lines.append("")

    lines.append("## Proposed frames and readings")
    for name, (_, _, frames) in coders.items():
        for f in frames:
            lines.append(f"- {name}: {f}")
    lines.append("")
    lines.append("## All split cells")
    for form, code, vals in disagreements:
        lines.append(f"- {form} {code}: " + ", ".join(f"{n} {v}" for n, v in vals.items()))
    (run / "COMPARISON.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {len(out)} coder cells; comparison in {run / 'COMPARISON.md'}")


if __name__ == "__main__":
    main()
