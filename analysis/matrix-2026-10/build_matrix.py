"""Build the 2026-10 determinative-pronoun matrix from the public 2021 file.

Applies only changes linked to a specific corpus record (applied_changes.csv)
and adds a whomever row derived from whoever (see WHOMEVER below). Values are
y, n, or marginal; the public file (analysis/data/matrix155-lingbuzz.csv) is
read, never written. Run from the repository root:
    python3 analysis/matrix-2026-10/build_matrix.py
"""
import csv, hashlib, pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = ROOT / "analysis/data/matrix155-lingbuzz.csv"
OUT = HERE / "matrix-2026-10.csv"

# whomever: whoever's 2021 row, with the cells by which the 2021 matrix
# separates whom_rel from who_rel (whom component, accusative, nominative,
# Monmorphemic, appears_in_subject), except appears_in_subject, which the
# corpus record keeps at y. The whoever component is n (the string isn't in
# whomever). Every other cell is inherited from whoever and not separately
# checked.
WHOMEVER_BASE = "whoever"
WHOMEVER = [
    ("whom", "y", "component, as in whom_rel"),
    ("whoever", "n", "component: whomever doesn't contain whoever"),
    ("accusative_case", "y", "as whom_rel; corpus: whomever after a preposition before a pronoun subject, 395 of 802 (17 Oct record)"),
    ("nominative_case", "n", "as whom_rel"),
    ("Monmorphemic", "n", "as whom_rel; whoever is already n"),
    ("appears_in_subject", "y", "corpus: whomever-headed fused relative as main-clause subject, 8 of about 51 (Whomever I chose for this experiment should be close to the mean, Southern Review 2015; 18 Oct record), unlike whom_rel"),
]
WHOMEVER_RECORDS = [
    "corpus/exclusion_tests/2026-10-17-brett-supplied-whoever-whomever.md",
    "corpus/exclusion_tests/2026-10-18-brett-supplied-whoever-whomever-gaps-and-matrix.md",
]

def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()

rows = list(csv.reader(SRC.open(encoding="utf-8-sig")))
head, body = rows[0], rows[1:]
idx = {f: i for i, f in enumerate(head)}
byform = {r[0]: r for r in body}

log = []
for c in csv.DictReader((HERE / "applied_changes.csv").open()):
    r = byform[c["form"]]; i = idx[c["feature"]]
    assert r[i] == c["old_value"], (c["form"], c["feature"], r[i])
    assert (ROOT / c["record"]).exists(), c["record"]
    r[i] = c["new_value"]
    log.append(f"| {c['form']} | {c['feature']} | {c['old_value']} → {c['new_value']} | {c['evidence']} | `{c['record']}` |")

new = list(byform[WHOMEVER_BASE]); new[0] = "whomever"
wlog = []
for f, v, why in WHOMEVER:
    old = new[idx[f]]; new[idx[f]] = v
    wlog.append(f"| {f} | {old} → {v} | {why} |")
for p in WHOMEVER_RECORDS: assert (ROOT / p).exists(), p
pos = [r[0] for r in body].index(WHOMEVER_BASE) + 1
body.insert(pos, new)

with OUT.open("w", newline="") as fh:
    w = csv.writer(fh); w.writerow([head[0].lstrip("﻿")] + head[1:]); w.writerows(body)

n_marg = sum(v == "marginal" for r in body for v in r[1:])
(HERE / "CHANGELOG.md").write_text(f"""# Matrix 2026-10: changes from the 2021 public matrix
<!-- SUMMARY: generated by build_matrix.py; every changed cell is tied to a corpus record or attested text; one row added (whomever) · status: built, analyses not rerun · updated: 2026-10-23 -->

Input: `analysis/data/matrix155-lingbuzz.csv` (SHA-256 `{sha(SRC)}`), unchanged.
Output: `matrix-2026-10.csv` (SHA-256 `{sha(OUT)}`), {len(body)} forms by {len(head)-1} features, values y, n, and marginal ({n_marg} marginal cells).

Rule (Brett, 23 October 2026): a change goes in only if it's linked to specific corpus evidence. The stage-1 proposals that rest on CGEL alone, on Claude's reasoning, or on judgments without a corpus record are held in `corrections.csv`, and so are both proposed new features. None of them is applied here.

## Changed cells

| Form | Feature | 2021 → 2026 | Evidence | Record |
|---|---|---|---|---|
""" + "\n".join(log) + f"""

## Added row: whomever

Derived from `{WHOMEVER_BASE}`'s 2021 row. The changed cells are the ones by which the 2021 matrix separates `whom_rel` from `who_rel`, except where a corpus record says otherwise. All other cells are inherited from `{WHOMEVER_BASE}` and haven't been checked separately. Among them is `accepts_genitive_apstrophe_s` = y, which no record attests for *whomever*. Records: {', '.join('`'+p+'`' for p in WHOMEVER_RECORDS)}.

| Feature | whoever → whomever | Basis |
|---|---|---|
""" + "\n".join(wlog) + """

## Marginal cells

Coded `marginal`, not forced to y or n. The analyses treat the coding of these cells as a fork (marginal as 0, as 1, and, for distance-based methods, as 0.5), added to the existing multiverse in `analysis/multiverse/`, and report every branch (Steegen, Tuerlinckx, Gelman & Vanpaemel 2016).
""")
print(OUT, len(body), "rows;", len(log), "changes;", n_marg, "marginal")
