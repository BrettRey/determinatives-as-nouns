#!/usr/bin/env python3
"""Do more categories beside Noun change the verdict? (24 Oct 2026)

Brett: "to do this properly, do we need prepositions and verbs too?", then, on
the first version of this check: "Yes, it's fake data, but it's got to be fake
in a way that makes sense for extra distinct categories". The first version let
the added categories vary on every column like nouns do, which made them
spuriously informative. This version gives each category the share of columns
on which it is n throughout, because the property doesn't apply to it:

  measured on the coded rows (24 Oct): all six adjectives n on 48 of 77 columns
  (0.62), all ten common nouns n on 29 of 77 (0.38). Proper nouns are given the
  common-noun share (only two are coded). Prepositions and adverbs are given the
  adjective share and verbs 0.85: assumptions, since none are coded.

Two cases: the columns we have, and the columns we have plus 20 diagnostic
columns for the added categories, on which they vary and the four nominal
categories are n throughout in 0.8 of columns. Same tests as simulate.py
(imported). Writes OUTGROUPS.md.
"""
from pathlib import Path

import numpy as np

import simulate as S

HERE = Path(__file__).resolve().parent
NA_SHARE = {"C": 0.38, "P": 0.38, "R": 0.0, "D": 0.0, "A": 0.62, "Prep": 0.62, "Adv": 0.62, "V": 0.85}
NOMINAL = {"C", "P", "R", "D"}


def trees(extra):
    return {"coordinate": {"root": ["Noun", "A"] + extra, "Noun": ["C", "P", "R", "D"]},
            "nested": {"root": ["Noun", "A"] + extra, "Noun": ["C", "P", "Pron"], "Pron": ["R", "D"]},
            "separate": {"root": ["Noun", "D", "A"] + extra, "Noun": ["C", "P", "R"]}}


def generate(rng, tree, sizes, ncol, nextra, mu, s_a, tau, sigma, pi):
    """As simulate.generate, but a category is n throughout on the columns that
    don't apply to it; nextra further columns are diagnostics for the added
    categories, n throughout for the nominal ones in 0.8 of them."""
    data = S.generate(rng, tree, sizes, ncol + nextra, mu, s_a, tau, sigma, pi)
    for leaf in S.LEAVES:
        off = rng.random(ncol) < NA_SHARE[leaf]
        if nextra:
            q = 0.8 if leaf in NOMINAL else 0.0
            off = np.concatenate([off, rng.random(nextra) < q])
        data[leaf][:, off] = 0.0
    return data


def main():
    rng = np.random.default_rng(S.SEED + 1)
    target, ncol_obs, nR, nD, ybar = S.observed()
    _, (mu, s_a, tau, sigma, pi), _ = S.calibrate(rng, target, ncol_obs, nR, nD, ybar)
    NSIM = 30
    rows = []
    cases = [("adjectives only", [], 0),
             ("plus prepositions and adverbs, our columns", ["Prep", "Adv"], 0),
             ("plus prepositions and adverbs, with 20 diagnostic columns for them", ["Prep", "Adv"], 20),
             ("plus prepositions, adverbs, and verbs, our columns", ["Prep", "Adv", "V"], 0)]
    for label, extra, nextra in cases:
        S.LEAVES = ["C", "P", "R", "D", "A"] + extra
        T = trees(extra)
        for samp, sizes0 in (("planned: 40 common nouns, 12 proper nouns, 12 adjectives", {"C": 40, "P": 12, "A": 12}),
                             ("large: 100 common nouns, 24 proper nouns, 24 adjectives", {"C": 100, "P": 24, "A": 24})):
            sizes = {"R": nR, "D": nD, **sizes0, **{x: 24 for x in extra}}
            for true in T:
                win = 0
                for _ in range(NSIM):
                    data = generate(rng, T[true], sizes, 140, nextra, mu, s_a, tau, sigma, pi)
                    sc = {t: S.logo_gls(T[t], data) for t in T}
                    win += max(sc, key=sc.get) == true
                rows.append((label, samp, true, win / NSIM))
    L = ["# Tree-recovery simulation: more categories beside Noun", "",
         "<!-- SUMMARY: whether adding prepositions, adverbs, and verbs changes how often the model-based group-out test recovers each tree, with each category n throughout on the columns that don't apply to it · status: for Brett · updated: 2026-10-24 -->", "",
         f"Generated by `outgroups.py` (seed {S.SEED + 1}, {NSIM} datasets per row, 140 columns, 24 forms in each added category). "
         "Each category is n throughout on a share of columns: adjectives 0.62 and common nouns 0.38 (measured on the coded rows), proper nouns as common nouns, prepositions and adverbs as adjectives, verbs 0.85 (assumed). Recovery: the share of datasets in which the test scores the generating tree highest.", "",
         "| categories added | sample | true tree | recovery |", "|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | {d:.2f} |" for a, b, c, d in rows]
    (HERE / "OUTGROUPS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[6:]))


if __name__ == "__main__":
    main()
