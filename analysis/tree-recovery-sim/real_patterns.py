#!/usr/bin/env python3
"""Companion to outgroups.py (24 Oct 2026): the applicability pattern of each
simulated column is copied from a real one. For each of the real columns with
coded adjective and common-noun rows, record which categories are n throughout
(common nouns, from the coders' majority on the ten coded rows; adjectives, on
the six; pronouns and determinatives, from the 2021 matrix; proper nouns are
given the common nouns' value); each simulated column draws one such pattern.
Run on all columns, and on the columns where no category is n throughout.
Writes REAL-PATTERNS.md."""
import csv
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

import outgroups as O
import simulate as S

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def patterns():
    cols = {r["column"]: r for r in csv.DictReader((ROOT / "analysis" / "codebook" / "columns.csv").open())}
    m = list(csv.reader((ROOT / "analysis" / "matrix-2026-10" / "matrix-2026-10.csv").open()))
    h = m[0]
    cat = {r["form"]: r["category"] for r in csv.DictReader((ROOT / "analysis" / "codebook" / "forms.csv").open())}
    use = [c for c in h[1:] if cols.get(c, {}).get("type") in ("possibility", "universal", "superseded")]
    adj = ["numerous", "multiple", "countless", "rich", "poor", "tall"]
    com = ["lot", "number", "numbers", "plenty", "dozen", "dozens", "majority", "dog", "dogs", "water"]
    v = defaultdict(lambda: defaultdict(list))
    for r in csv.DictReader((ROOT / "analysis" / "cell-ledger" / "cells.csv").open()):
        if r["form"] in adj + com and r["column"] in use and r["proposer"].startswith("blind coder") and r["frame"] == "default":
            v[r["column"]][r["form"]].append("n" if r["value"] == "x" else r["value"])
    maj = lambda xs: Counter(xs).most_common(1)[0][0]
    out = []
    for c in use:
        a = [maj(v[c][f]) for f in adj if v[c][f]]
        n = [maj(v[c][f]) for f in com if v[c][f]]
        if len(a) < 4 or len(n) < 6:
            continue
        i = h.index(c)
        R = [r[i] for r in m[1:] if cat.get(r[0]) == "pronoun"]
        D = [r[i] for r in m[1:] if cat.get(r[0]) == "determinative"]
        alln = lambda xs: all(x == "n" for x in xs)
        out.append({"C": alln(n), "P": alln(n), "R": alln(R), "D": alln(D), "A": alln(a)})
    return out


def main():
    pats = patterns()
    combo = Counter(tuple(k for k in "CPRDA" if p[k]) for p in pats)
    rng = np.random.default_rng(S.SEED + 3)
    target, ncol_obs, nR, nD, ybar = S.observed()
    _, (mu, s_a, tau, sigma, pi), _ = S.calibrate(rng, target, ncol_obs, nR, nD, ybar)
    S.LEAVES = ["C", "P", "R", "D", "A"]
    T = O.trees([])
    NSIM, rows = 30, []
    for which in ("all columns", "only columns no category is n throughout on"):
        for ncol in (140, 400):
            for samp, sizes0 in (("planned: 40 common nouns, 12 proper nouns, 12 adjectives", {"C": 40, "P": 12, "A": 12}),
                                 ("large: 100 common nouns, 24 proper nouns, 24 adjectives", {"C": 100, "P": 24, "A": 24})):
                sizes = {"R": nR, "D": nD, **sizes0}
                for true in T:
                    win, kept = 0, []
                    for _ in range(NSIM):
                        data = S.generate(rng, T[true], sizes, ncol, mu, s_a, tau, sigma, pi)
                        draw = [pats[j] for j in rng.integers(0, len(pats), ncol)]
                        for l in S.LEAVES:
                            off = np.array([p[l] for p in draw])
                            data[l][:, off] = 0.0
                        if which != "all columns":
                            keep = ~np.array([any(p.values()) for p in draw])
                            data = {l: data[l][:, keep] for l in S.LEAVES}
                        kept.append(data["C"].shape[1])
                        sc = {t: S.logo_gls(T[t], data) for t in T}
                        win += max(sc, key=sc.get) == true
                    rows.append((which, ncol, samp, true, win / NSIM, float(np.mean(kept))))
    L = ["# Tree-recovery simulation: applicability copied from the real columns", "",
         "<!-- SUMMARY: recovery of each tree when each simulated column copies which categories are n throughout on a real column · status: for Brett · updated: 2026-10-24 -->", "",
         f"Generated by `real_patterns.py` (seed {S.SEED + 3}, {NSIM} datasets per row). {len(pats)} real columns have enough coded adjective and common-noun rows. "
         "Patterns (categories n throughout: count of columns): " + "; ".join(f"{'+'.join(k) or 'none'}: {n}" for k, n in combo.most_common()) + ".", "",
         "| columns used | columns generated | sample | true tree | recovery | columns kept (mean) |", "|---|---|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | {d} | {e:.2f} | {f:.0f} |" for a, b, c, d, e, f in rows]
    (HERE / "REAL-PATTERNS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[4:]))


if __name__ == "__main__":
    main()
