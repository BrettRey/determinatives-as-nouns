#!/usr/bin/env python3
"""Companion to outgroups.py (24 Oct 2026): the same generator, scored only on
the columns that apply to every category (no category n throughout because the
property can't apply to it). Tests whether the bias toward the nested tree comes
from the columns that apply only to pronouns and determinatives. Writes GENERAL-ONLY.md."""
from pathlib import Path

import numpy as np

import outgroups as O
import simulate as S

HERE = Path(__file__).resolve().parent


def main():
    rng = np.random.default_rng(S.SEED + 2)
    target, ncol_obs, nR, nD, ybar = S.observed()
    _, (mu, s_a, tau, sigma, pi), _ = S.calibrate(rng, target, ncol_obs, nR, nD, ybar)
    S.LEAVES = ["C", "P", "R", "D", "A"]
    T = O.trees([])
    NSIM, rows = 30, []
    for ncol in (140, 400):
        for samp, sizes0 in (("planned: 40 common nouns, 12 proper nouns, 12 adjectives", {"C": 40, "P": 12, "A": 12}),
                             ("large: 100 common nouns, 24 proper nouns, 24 adjectives", {"C": 100, "P": 24, "A": 24})):
            sizes = {"R": nR, "D": nD, **sizes0}
            for true in T:
                win, kept = 0, []
                for _ in range(NSIM):
                    full = S.generate(rng, T[true], sizes, ncol, mu, s_a, tau, sigma, pi)
                    off = {l: rng.random(ncol) < O.NA_SHARE[l] for l in S.LEAVES}
                    general = ~np.any(np.vstack(list(off.values())), axis=0)
                    data = {l: full[l][:, general] for l in S.LEAVES}
                    kept.append(general.sum())
                    sc = {t: S.logo_gls(T[t], data) for t in T}
                    win += max(sc, key=sc.get) == true
                rows.append((ncol, samp, true, win / NSIM, float(np.mean(kept))))
    L = ["# Tree-recovery simulation: only the columns that apply to every category", "",
         "<!-- SUMMARY: recovery of each tree when the test uses only the columns that apply to all categories · status: for Brett · updated: 2026-10-24 -->", "",
         f"Generated by `general_only.py` (seed {S.SEED + 2}, {NSIM} datasets per row). Columns are generated as in `outgroups.py`, then only those on which no category is n throughout for want of applicability are kept (shares as there: common and proper nouns 0.38, adjectives 0.62).", "",
         "| columns generated | sample | true tree | recovery | columns kept (mean) |", "|---|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | {d:.2f} | {e:.0f} |" for a, b, c, d, e in rows]
    (HERE / "GENERAL-ONLY.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[6:]))


if __name__ == "__main__":
    main()
